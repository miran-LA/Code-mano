// Configuración de I2C1 para STM32F401 (PB6=SCL, PB7=SDA)
static void I2C1_Init(void) {
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;

    // Configurar PB6 y PB7 en Función Alternativa (AF4)
    GPIOB->MODER &= ~((3U << (6 * 2)) | (3U << (7 * 2)));
    GPIOB->MODER |=  ((2U << (6 * 2)) | (2U << (7 * 2)));

    GPIOB->OTYPER |= (1U << 6) | (1U << 7); // Open-Drain
    GPIOB->OSPEEDR |= ((3U << (6 * 2)) | (3U << (7 * 2)));

    GPIOB->PUPDR &= ~((3U << (6 * 2)) | (3U << (7 * 2)));
    GPIOB->PUPDR |=  ((1U << (6 * 2)) | (1U << (7 * 2))); // Pull-up interno

    // Selección de AF4 para I2C1 en AFRL (Pines PB6 y PB7)
    GPIOB->AFR[0] &= ~((15U << (6 * 4)) | (15U << (7 * 4)));
    GPIOB->AFR[0] |=  ((4U  << (6 * 4)) | (4U  << (7 * 4)));

    // Reiniciar periférico I2C1
    I2C1->CR1 |= I2C_CR1_SWRST;
    I2C1->CR1 &= ~I2C_CR1_SWRST;

    // Configuración I2C Standard Mode (100kHz)
    I2C1->CR2 = 16;     // FREQ = 16 MHz
    I2C1->CCR = 80;     // 100 kHz
    I2C1->TRISE = 17;   // Max Rise Time

    I2C1->CR1 |= I2C_CR1_PE; // Habilitar I2C1
}

// Envío de comandos con protección Anti-Bloqueo
static void OLED_WriteCmd(uint8_t cmd) {
    uint32_t timeout;

    I2C1->CR1 |= I2C_CR1_START;
    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_SB) && --timeout);
    if (!timeout) return;

    I2C1->DR = OLED_ADDR;
    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_ADDR) && --timeout);
    if (!timeout) return;
    (void)I2C1->SR2; // Limpia flag ADDR

    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_TXE) && --timeout);
    if (!timeout) return;
    I2C1->DR = 0x00; // Byte de Control: Comando

    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_TXE) && --timeout);
    if (!timeout) return;
    I2C1->DR = cmd;

    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_BTF) && --timeout);
    I2C1->CR1 |= I2C_CR1_STOP;
}

// Envío continuo de datos a la RAM con protección Anti-Bloqueo
static void OLED_WriteDataStream(const uint8_t *data, uint16_t size) {
    uint32_t timeout;

    I2C1->CR1 |= I2C_CR1_START;
    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_SB) && --timeout);
    if (!timeout) return;

    I2C1->DR = OLED_ADDR;
    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_ADDR) && --timeout);
    if (!timeout) return;
    (void)I2C1->SR2;

    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_TXE) && --timeout);
    if (!timeout) return;
    I2C1->DR = 0x40; // Byte de Control: Datos

    for (uint16_t i = 0; i < size; i++) {
        timeout = OLED_TIMEOUT;
        while (!(I2C1->SR1 & I2C_SR1_TXE) && --timeout);
        if (!timeout) return;
        I2C1->DR = data[i];
    }

    timeout = OLED_TIMEOUT;
    while (!(I2C1->SR1 & I2C_SR1_BTF) && --timeout);
    I2C1->CR1 |= I2C_CR1_STOP;
}

void OLED_Init(void) {
    I2C1_Init();
    for (volatile int i = 0; i < 100000; i++); // Pequeña pausa de inicio

    OLED_WriteCmd(0xAE); // Display OFF
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x02); // Modo página
    OLED_WriteCmd(0xA1);
    OLED_WriteCmd(0xC8);
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4);
    OLED_WriteCmd(0xA6);
    OLED_WriteCmd(0xAF); // Display ON
}

void OLED_Clear(void) {
    uint8_t zero_buf[128] = {0};
    for (uint8_t page = 0; page < 8; page++) {
        OLED_SetCursor(page, 0);
        OLED_WriteDataStream(zero_buf, 128);
    }
}

void OLED_SetCursor(uint8_t page, uint8_t col) {
    OLED_WriteCmd(0xB0 + (page & 0x07));
    OLED_WriteCmd(0x00 + (col & 0x0F));
    OLED_WriteCmd(0x10 + ((col >> 4) & 0x0F));
}

void OLED_PutChar(char ch, uint8_t page, uint8_t col) {
    if (ch < 32 || ch > 126) ch = ' ';
    OLED_SetCursor(page, col);

    uint8_t char_data[6];
    for (int i = 0; i < 5; i++) {
        char_data[i] = Font5x7[ch - 32][i];
    }
    char_data[5] = 0x00; // Espacio entre caracteres

    OLED_WriteDataStream(char_data, 6);
}

void OLED_PrintStr(const char *str, uint8_t page, uint8_t col) {
    while (*str) {
        if (col > 122) {
            col = 0;
            page++;
        }
        OLED_PutChar(*str, page, col);
        col += 6;
        str++;
    }
}

void OLED_PrintNum(uint32_t num, uint8_t page, uint8_t col) {
    char buf[11];
    int i = 0;
    if (num == 0) {
        buf[i++] = '0';
    } else {
        while (num > 0) {
            buf[i++] = (num % 10) + '0';
            num /= 10;
        }
    }
    buf[i] = '\0';

    // Invertir cadena
    for (int j = 0; j < i / 2; j++) {
        char temp = buf[j];
        buf[j] = buf[i - 1 - j];
        buf[i - 1 - j] = temp;
    }

    OLED_PrintStr(buf, page, col);
}
